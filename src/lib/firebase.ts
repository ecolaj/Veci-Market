    const permission = await Notification.requestPermission();
    if (permission === 'granted') {
      const currentToken = await getToken(messaging, { 
        // user needs to add VAPID key in production
        // vapidKey: 'YOUR_PUBLIC_VAPID_KEY_HERE' 
      });
      if (currentToken) {
        return currentToken;
      }
    }
